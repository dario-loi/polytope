"""streamlit integration: text for ``.streamlit/config.toml``.

Streamlit reads its theme from a config file, so this module only produces
text and does not import streamlit. The custom font syntax used here
("Name:URL") needs streamlit 1.50 or newer; pass ``google_fonts=False`` for
older releases or offline apps.

Usage::

    from polytope_theme.streamlit_theme import write_config
    write_config(mode="light")   # writes .streamlit/config.toml
"""

from __future__ import annotations

import json
from pathlib import Path

from ._tokens import CATEGORICAL, COLORS, FONTS

__all__ = ["config_toml", "write_config"]

_MODES = ("light", "dark")

_MARKER = "# Generated by polytope_theme.streamlit_theme.config_toml()."

_FONT_URLS = {
    "text": "https://fonts.googleapis.com/css2?family=Libre+Franklin:wght@400;600;700&display=swap",
    "mono": "https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;700&display=swap",
}


def _toml(value: object) -> str:
    # JSON strings and arrays of strings are valid TOML for ASCII content.
    return json.dumps(value)


def config_toml(mode: str = "light", *, google_fonts: bool = True) -> str:
    """Return the ``[theme]`` table for ``mode`` as TOML text.

    Sets base, primaryColor, backgroundColor, secondaryBackgroundColor,
    textColor, linkColor, borderColor, baseRadius, font, codeFont and
    chartCategoricalColors. Headings use the text font; streamlit applies
    ``headingFont`` to every heading level, and Ultra is meant for titles only.
    """
    if mode not in _MODES:
        raise ValueError(f"mode must be one of {_MODES!r}, got {mode!r}")
    c = COLORS[mode]
    if google_fonts:
        font = f"'{FONTS['text']}':{_FONT_URLS['text']}"
        code_font = f"'{FONTS['mono']}':{_FONT_URLS['mono']}"
    else:
        font, code_font = "sans-serif", "monospace"

    rows = [
        ("base", mode),
        ("primaryColor", c["accent"]),
        ("backgroundColor", c["bg"]),
        ("secondaryBackgroundColor", c["surface_sunken"]),
        ("textColor", c["text"]),
        ("linkColor", c["link"]),
        ("borderColor", c["rule"]),
        ("baseRadius", "none"),
        ("font", font),
        ("codeFont", code_font),
        ("chartCategoricalColors", list(CATEGORICAL[mode])),
    ]
    lines = [
        f"# Polytope, streamlit theme ({mode}).",
        _MARKER,
        "[theme]",
    ]
    lines += [f"{key} = {_toml(value)}" for key, value in rows]
    return "\n".join(lines) + "\n"


def write_config(
    path: str | Path = ".streamlit/config.toml",
    mode: str = "light",
    *,
    google_fonts: bool = True,
    overwrite: bool = False,
) -> Path:
    """Write ``config_toml(mode)`` to ``path``, creating parent folders.

    A file previously written by this function is replaced. Any other existing
    file raises FileExistsError unless ``overwrite=True``, since streamlit
    keeps server and client settings in the same file. Returns the path.
    """
    target = Path(path)
    if target.exists() and not overwrite:
        current = target.read_text(encoding="utf-8")
        if current.strip() and _MARKER not in current:
            raise FileExistsError(
                f"{target} exists and was not written by polytope_theme. "
                "Pass overwrite=True to replace it, or paste config_toml() into it."
            )
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(config_toml(mode, google_fonts=google_fonts), encoding="utf-8")
    return target
