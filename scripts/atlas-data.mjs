// Regenerates the files the Atlas draws with. Run it only to change the map data or the
// d3-geo version; the outputs are committed, so builds and installs never need it.
//
//   npm install --no-save d3-geo@3 topojson-client@3 topojson-server@3 topojson-simplify@3 esbuild
//   node scripts/atlas-data.mjs
//
// Writes:
//   css/js/atlas-geo.js        the parts of d3-geo the Atlas uses, bundled as one ES module
//   css/js/atlas-world-110m.js country outlines for the whole-globe view
//   css/js/atlas-world-50m.js  country outlines for close views
//
// The outlines are Natural Earth's 1:10m countries as the United States government recognizes
// them (the "usa" point of view), simplified to two levels of detail. Natural Earth publishes
// points of view only at 1:10m, so both levels are made from it. The file names keep the
// scale each level matches.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { geoArea } from "d3-geo";
import { topology } from "topojson-server";
import { presimplify, simplify, quantile, sphericalTriangleArea } from "topojson-simplify";
import { mergeArcs, quantize } from "topojson-client";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "css/js");
const dir = (name) => join(root, "node_modules", name);
const pkg = (name) => JSON.parse(readFileSync(join(dir(name), "package.json"), "utf8"));
const license = (name) => readFileSync(join(dir(name), "LICENSE"), "utf8").trim();
const comment = (text) => text.split("\n").map((l) => `// ${l}`.trimEnd()).join("\n");

// d3-geo: only what css/js/atlas-core.js imports, minified. ISC asks for the notices in copies.
const geo = await build({
  stdin: { contents: 'export { geoOrthographic, geoPath, geoGraticule10, geoInterpolate, geoDistance, geoCentroid, geoContains } from "d3-geo";', resolveDir: root },
  bundle: true, format: "esm", minify: true, legalComments: "none", write: false,
});
writeFileSync(join(out, "atlas-geo.js"), [
  `// d3-geo ${pkg("d3-geo").version} and d3-array ${pkg("d3-array").version}, bundled for the Atlas by scripts/atlas-data.mjs. Do not edit.`,
  "//",
  comment(license("d3-geo")),
  "//",
  comment(license("d3-array")),
  geo.outputFiles[0].text,
].join("\n"));

// Natural Earth, pinned to a release.
const NE = "v5.1.1";
const source = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${NE}/geojson/ne_10m_admin_0_countries_usa.geojson`;
const res = await fetch(source);
if (!res.ok) throw new Error(`could not fetch ${source}: ${res.status}`);
const countries = (await res.json()).features;

// One level of detail. Islands smaller than minKm2 are dropped, except each country's largest
// piece, so every country still has a shape to fill. Then the outlines keep the points that
// carry the most shape, about `points` of them, rounded to a 30000-step grid. The land is the
// union of the countries, sharing their arcs.
function level(minKm2, points) {
  const min = minKm2 / 6371 ** 2;
  const features = countries.map((f) => {
    const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
    const areas = polys.map((p) => geoArea({ type: "Polygon", coordinates: p }));
    const largest = areas.indexOf(Math.max(...areas));
    const kept = polys.filter((p, i) => i === largest || areas[i] >= min);
    return { type: "Feature", properties: {}, geometry: { type: "MultiPolygon", coordinates: kept } };
  });
  let topo = presimplify(topology({ countries: { type: "FeatureCollection", features } }), sphericalTriangleArea);
  const total = topo.arcs.reduce((n, a) => n + a.length, 0);
  topo = simplify(topo, quantile(topo, Math.min(1, points / total)));
  topo.arcs = topo.arcs.map((arc) => arc.map(([x, y]) => [x, y]));
  for (const g of topo.objects.countries.geometries) delete g.properties;
  topo.objects.land = { type: "GeometryCollection", geometries: [mergeArcs(topo, topo.objects.countries.geometries)] };
  return quantize(topo, 3e4);
}

const header = (note) => [
  `// Natural Earth ${NE} countries, United States point of view, ${note}. Generated by scripts/atlas-data.mjs.`,
  "// Natural Earth is in the public domain (naturalearthdata.com).",
].join("\n");
for (const [name, minKm2, points, note] of [
  ["110m", 2500, 7500, "simplified for the whole globe"],
  ["50m", 150, 20000, "simplified for close views"],
]) {
  const topo = level(minKm2, points);
  writeFileSync(join(out, `atlas-world-${name}.js`), `${header(note)}\nexport default ${JSON.stringify(topo)};\n`);
  console.log(`atlas-world-${name}.js: ${topo.arcs.reduce((n, a) => n + a.length, 0)} points, ${topo.objects.countries.geometries.length} countries`);
}
